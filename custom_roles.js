          return {
            info: '保护 ' + nm(t1) + ' ／ 醉酒 ' + nm(t2),
            detail: '本夜：' + nm(t1) + ' 免受中毒与醉酒；' + nm(t2) + ' 醉酒。' + e,
            say: '点头确认你指定的两人'
          };
